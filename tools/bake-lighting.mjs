import { writeFile, mkdir } from 'node:fs/promises';
import { BUILDING, WALLS, FURNITURE } from '../js/museum/layout.js';
import { FLOOR_REGIONS, floorEmitters } from '../js/museum/lighting-layout.js';

const AO_DISTANCE = 2.4;
// A fixed cosine-weighted hemisphere gives reproducible, diffuse contact shade.
const directions = Array.from({ length: 32 }, (_, i) => {
  const u = (i + .5) / 32, angle = i * Math.PI * (3 - Math.sqrt(5));
  return [Math.cos(angle) * Math.sqrt(u), Math.sqrt(1 - u), Math.sin(angle) * Math.sqrt(u)];
});
const heights = { screen: 2, reception: 1.22, directory: 1.5, lamp: 1.55,
  console: .85, reading: .76, editorial: .76, consultation: .76,
  coffee: .42, lowtable: .42, ottoman: .42, lounge: .85, temu: .8 };
// Static collision footprints approximate the furniture, while walls use the
// actual layout. Nearby geometry only: this avoids baking adjacent rooms' shade.
const blockers = [
  ...WALLS.map(wall => ({ ...wall, height: BUILDING.height })),
  ...FURNITURE.map(piece => ({ ...piece, height: heights[piece.kind] ?? .8 })),
];

export function floorPoint(region, u, v) {
  // PlaneGeometry rotated -PI/2: UV (0,0) is minX, maxZ. DataTexture is not flipped.
  return { x: region.x + (u - .5) * region.width, z: region.z + (.5 - v) * region.depth };
}

function rayDistance(x, z, direction, box) {
  let near = 0, far = AO_DISTANCE;
  const origins = [x, .015, z], minimum = [box.minX, 0, box.minZ];
  const maximum = [box.maxX, box.height, box.maxZ];
  for (let axis = 0; axis < 3; axis++) {
    const d = direction[axis], origin = origins[axis];
    if (Math.abs(d) < 1e-8) {
      if (origin < minimum[axis] || origin > maximum[axis]) return Infinity;
      continue;
    }
    const a = (minimum[axis] - origin) / d, b = (maximum[axis] - origin) / d;
    near = Math.max(near, Math.min(a, b));
    far = Math.min(far, Math.max(a, b));
    if (near > far) return Infinity;
  }
  return near;
}

export function floorVisibility(x, z, geometry = blockers) {
  const nearby = geometry.filter(box => x >= box.minX - AO_DISTANCE && x <= box.maxX + AO_DISTANCE &&
    z >= box.minZ - AO_DISTANCE && z <= box.maxZ + AO_DISTANCE);
  if (!nearby.length) return 1;
  let occluded = 0;
  for (const direction of directions) {
    let distance = Infinity;
    for (const box of nearby) distance = Math.min(distance, rayDistance(x, z, direction, box));
    occluded += Math.max(0, 1 - distance / AO_DISTANCE);
  }
  return 1 - .8 * occluded / directions.length;
}

export function sampleEmitters(sources) {
  return sources.flatMap(source => {
    const nx = Math.max(1, Math.ceil(source.width / 2.5));
    const nz = Math.max(1, Math.ceil(source.depth / 2.5));
    return Array.from({ length: nx * nz }, (_, i) => ({
      x: source.x + ((i % nx + .5) / nx - .5) * source.width,
      z: source.z + ((Math.floor(i / nx) + .5) / nz - .5) * source.depth,
      height: source.height, power: source.power / (nx * nz),
    }));
  });
}

export function floorIrradiance(x, z, samples) {
  let light = .12;
  for (const source of samples) {
    const height2 = source.height ** 2;
    const distance2 = (source.x - x) ** 2 + (source.z - z) ** 2 + height2;
    light += source.power * height2 / (distance2 * distance2);
  }
  return Math.min(.95, light);
}

export function bakeFloor(region, width, height) {
  // Neutral ceiling emitters share one tint. Store irradiance in one channel,
  // then expand it on upload, avoiding three redundant colour channels in JS.
  const light = new Uint8Array(width * height), occlusion = new Uint8Array(width * height);
  const samples = sampleEmitters(floorEmitters(region));
  for (let row = 0; row < height; row++) for (let col = 0; col < width; col++) {
    const { x, z } = floorPoint(region, (col + .5) / width, (row + .5) / height);
    const value = floorIrradiance(x, z, samples), index = row * width + col;
    light[index] = Math.round(value * 255);
    occlusion[index] = Math.round(floorVisibility(x, z) * 255);
  }
  return { width, height, light, occlusion };
}

export async function bakeGalleryLighting(root = 'vendor') {
  const floors = {};
  for (const region of FLOOR_REGIONS) {
    const { width, height, light, occlusion } = bakeFloor(region,
      region.hallIndex === undefined ? 32 : 64, region.hallIndex === undefined ? 448 : 76);
    floors[region.id] = { width, height,
      light: Buffer.from(light).toString('base64'), occlusion: Buffer.from(occlusion).toString('base64') };
  }
  await mkdir(root, { recursive: true });
  await writeFile(`${root}/gallery-lightmaps.js`, `// Generated by tools/bake-lighting.mjs. Linear light, independent of artwork.\nexport const FLOOR_LIGHTMAPS=${JSON.stringify(floors)};\n`);
}
